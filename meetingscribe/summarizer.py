LANGUAGE_NAMES = {
    "ru": "Русский",
    "en": "English",
    "auto": "Авто",
}


def _format_duration(seconds: int) -> str:
    h = seconds // 3600
    m = (seconds % 3600) // 60
    if h > 0:
        return f"{h} ч {m} мин"
    return f"{m} мин"


def build_prompt(transcript: str, meeting_type: str, **kwargs) -> str:
    template = PROMPTS.get(meeting_type, PROMPTS["work"])
    return template.format(
        transcript=transcript,
        date=kwargs.get("date", datetime.now().strftime("%Y-%m-%d %H:%M")),
        duration=kwargs.get("duration", "N/A"),
        language=kwargs.get("language", "Русский"),
    )


def summarize(
    transcript: str,
    output_path: Path,
    meeting_type: str,
    language: str,
    duration_seconds: int,
    api_key: str,
    model: str = "claude-sonnet-4-6",
) -> str | None:
    if not api_key:
        return None

    prompt = build_prompt(
        transcript,
        meeting_type,
        date=datetime.now().strftime("%Y-%m-%d %H:%M"),
        duration=_format_duration(duration_seconds),
        language=LANGUAGE_NAMES.get(language, language),
    )

    client = anthropic.Anthropic(api_key=api_key)
    response = client.messages.create(
        model=model,
        max_tokens=4096,
        messages=[{"role": "user", "content": prompt}],
    )

    summary_text = response.content[0].text
    output_path.write_text(summary_text, encoding="utf-8")

    return summary_text
